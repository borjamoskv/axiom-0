use super::RuntimeTerm;
use alloc::{borrow::ToOwned, format, string::String};
use core::fmt;

/// A runtime term cannot be represented by the scalar C99 backend.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CodegenError {
    InvalidFunctionName,
    UnboundVariable(usize),
    UnsupportedTerm(&'static str),
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidFunctionName => f.write_str("invalid C function name"),
            Self::UnboundVariable(level) => write!(f, "unbound runtime variable {level}"),
            Self::UnsupportedTerm(kind) => write!(f, "unsupported runtime term: {kind}"),
        }
    }
}

impl core::error::Error for CodegenError {}

/// Emits standalone scalar C99 code, or a compile-time diagnostic for unsupported terms.
/// Use [`try_emit_c_code`] to handle unsupported terms without invoking a C compiler.
pub fn emit_c_code(term: &RuntimeTerm, fn_name: &str) -> String {
    try_emit_c_code(term, fn_name)
        .unwrap_or_else(|error| format!("#error AXIOM-0 code generation failed: {error}\n"))
}

/// Emits scalars, branches, projections of literal pairs and natural-number recursion.
/// Higher-order terms and pair-valued results are rejected instead of replaced by zero.
pub fn try_emit_c_code(term: &RuntimeTerm, fn_name: &str) -> Result<String, CodegenError> {
    let mut name = fn_name.bytes();
    if !name
        .next()
        .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
        || !name.all(|b| b.is_ascii_alphanumeric() || b == b'_')
    {
        return Err(CodegenError::InvalidFunctionName);
    }
    let mut emitter = Emitter::default();
    let body = emitter.expression(term, 0)?;
    let result_type = if matches!(term, RuntimeTerm::Bool(_)) {
        "bool"
    } else {
        "uint64_t"
    };
    let successor = if emitter.needs_successor {
        "static inline uint64_t __axiom0_succ(uint64_t n) {\n    return n == UINT64_MAX ? n : n + 1ULL;\n}\n\n"
    } else {
        ""
    };
    Ok(format!(
        "// Generated by AXIOM-0's scalar C99 backend.\n#include <stdint.h>\n#include <stdbool.h>\n\n{successor}{}{result_type} {fn_name}() {{\n    return {body};\n}}\n",
        emitter.helpers
    ))
}

#[derive(Default)]
struct Emitter {
    helpers: String,
    next_helper: usize,
    needs_successor: bool,
}

impl Emitter {
    fn expression(&mut self, term: &RuntimeTerm, depth: usize) -> Result<String, CodegenError> {
        Ok(match term {
            RuntimeTerm::Unit | RuntimeTerm::Erased => "0ULL".to_owned(),
            RuntimeTerm::Bool(b) => (if *b { "true" } else { "false" }).to_owned(),
            RuntimeTerm::Nat(n) => format!("{n}ULL"),
            RuntimeTerm::Succ(inner) => {
                self.needs_successor = true;
                format!("__axiom0_succ({})", self.expression(inner, depth)?)
            }
            RuntimeTerm::Var(level) => {
                if *level >= depth {
                    return Err(CodegenError::UnboundVariable(*level));
                }
                format!("x_{level}")
            }
            RuntimeTerm::If { cond, conseq, alt } => format!(
                "(({}) ? ({}) : ({}))",
                self.expression(cond, depth)?,
                self.expression(conseq, depth)?,
                self.expression(alt, depth)?
            ),
            RuntimeTerm::Fst(pair) | RuntimeTerm::Snd(pair) => {
                let RuntimeTerm::Pair(first, second) = pair.as_ref() else {
                    return Err(CodegenError::UnsupportedTerm("dynamic pair projection"));
                };
                self.expression(
                    if matches!(term, RuntimeTerm::Fst(_)) {
                        first
                    } else {
                        second
                    },
                    depth,
                )?
            }
            RuntimeTerm::NatRec { base, step, target } => {
                let RuntimeTerm::Lam(outer) = step.as_ref() else {
                    return Err(CodegenError::UnsupportedTerm("non-lambda recursion step"));
                };
                let RuntimeTerm::Lam(body) = outer.as_ref() else {
                    return Err(CodegenError::UnsupportedTerm("recursion step arity"));
                };
                let id = self.next_helper;
                self.next_helper += 1;
                let base_c = self.expression(base, depth)?;
                let target_c = self.expression(target, depth)?;
                let body_c = self.expression(body, depth + 2)?;
                let mut params = String::new();
                let mut args = String::new();
                let mut unused = String::new();
                for level in 0..depth {
                    params.push_str(&format!("uint64_t x_{level}, "));
                    args.push_str(&format!("x_{level}, "));
                    unused.push_str(&format!("    (void)x_{level};\n"));
                }
                params.push_str("uint64_t _base, uint64_t _target");
                args.push_str(&format!("{base_c}, {target_c}"));
                let acc = depth + 1;
                self.helpers.push_str(&format!(
                    "static inline uint64_t __axiom0_natrec_{id}({params}) {{\n{unused}    uint64_t x_{acc} = _base;\n    for (uint64_t x_{depth} = 0ULL; x_{depth} < _target; ++x_{depth}) {{\n        x_{acc} = {body_c};\n    }}\n    return x_{acc};\n}}\n\n"
                ));
                format!("__axiom0_natrec_{id}({args})")
            }
            RuntimeTerm::App(..) => return Err(CodegenError::UnsupportedTerm("application")),
            RuntimeTerm::Lam(..) => return Err(CodegenError::UnsupportedTerm("lambda")),
            RuntimeTerm::Closure(..) => return Err(CodegenError::UnsupportedTerm("closure")),
            RuntimeTerm::Pair(..) => {
                return Err(CodegenError::UnsupportedTerm("pair-valued result"));
            }
        })
    }
}
